import { before, describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { nativeGrammarRuleConcepts } from '#meta-language';
import {
  CLASSIFIER_PATH, INVENTORY_PATH, buildLanguageConstructInventory, classifyConstructs,
  renderLanguageConstructInventory,
} from '../src/rml-language-inventory.mjs';

const read = path => readFileSync(new URL(`../../${path}`, import.meta.url), 'utf8');
const classifier = JSON.parse(read(CLASSIFIER_PATH));

describe('four-language construct inventory', () => {
  let inventory;
  before(() => { inventory = buildLanguageConstructInventory(); });

  it('is regenerated byte-for-byte from the classifier, upstream grammars and corpus', () => {
    assert.equal(read(INVENTORY_PATH), renderLanguageConstructInventory(inventory),
      'stale inventory: run node scripts/language-construct-inventory.mjs --write');
  });

  it('classifies every upstream grammar construct on exactly one declared axis', () => {
    assert.deepEqual(inventory.languages.map(language => language.language), ['JavaScript', 'Rust', 'Lean', 'Rocq']);
    for (const language of inventory.languages) {
      const rules = nativeGrammarRuleConcepts(language.grammar);
      assert.equal(language.rules, rules.length);
      assert.deepEqual(language.constructs.map(row => row[0]), rules.map(rule => rule.rule));
      assert.deepEqual(language.unclassified, [], language.language);
      assert.deepEqual(language.deadPatterns, [], language.language);
      assert.ok(language.constructs.every(row => Object.hasOwn(classifier.axes, row[3])), language.language);
      assert.equal(Object.values(language.byAxis).reduce((total, axis) => total + axis.constructs, 0), language.rules);
      assert.ok(language.constructs.every(row => ['normal', 'silent', 'token'].includes(row[2])), language.language);
    }
  });

  it('records native-grammar refusals and unexercised constructs instead of hiding them', () => {
    const byName = Object.fromEntries(inventory.languages.map(language => [language.language, language]));
    for (const language of inventory.languages) assert.deepEqual(language.unexpectedAcceptance, [], language.language);
    assert.ok(byName.Rocq.refusedPrograms.includes('rocq-refused: CoFixpoint has no native grammar rule'));
    assert.ok(byName.Lean.refusedPrograms.includes('lean-refused: structured induction alternatives'));
    assert.ok(byName.Lean.refusedPrograms.includes('js/vendor/meta-language/parity/fixtures/translation-corpus/project.lean'));
    for (const language of inventory.languages) {
      assert.equal(language.unexercised.length, language.observable - language.exercised);
      assert.ok(language.exercised / language.observable > 0.85, `${language.language} corpus exercises too little`);
    }
  });

  it('fails on a construct no pattern classifies and on a pattern that matches nothing', () => {
    const { patterns, grammar } = classifier.languages.Rust;
    const rules = [...nativeGrammarRuleConcepts(grammar), { rule: 'brand_new_construct', concept: 'grammar.brand-new' }];
    const unclassified = classifyConstructs(patterns, rules);
    assert.deepEqual(unclassified.unclassified, ['brand_new_construct']);
    const dead = classifyConstructs([...patterns, ['types', '^never_a_rule$']], nativeGrammarRuleConcepts(grammar));
    assert.deepEqual(dead.deadPatterns, ['types']);
    const shadowed = classifyConstructs([['structure', '.*'], ...patterns], nativeGrammarRuleConcepts(grammar));
    assert.equal(shadowed.deadPatterns.length, patterns.length);
  });
});
