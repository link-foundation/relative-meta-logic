import { readFileSync, writeFileSync } from 'node:fs';

import {
  compileCombinatorSource,
  serializeCombinatorSource,
} from './combinator-source.mjs';

const source = readFileSync(
  new URL('../lib/meta-theory/fixed-point-source.lino', import.meta.url),
  'utf8',
);
const { metadata } = compileCombinatorSource(source);
const serialized = serializeCombinatorSource(source);

writeFileSync(
  new URL('../lib/meta-theory/fixed-point.ski', import.meta.url),
  serialized,
);
writeFileSync(
  new URL('../js/src/rml-combinator-kernel-data.mjs', import.meta.url),
  `// Generated by scripts/generate-combinator-kernel.mjs; do not edit.\n` +
    `export const KERNEL_SOURCE_METADATA = Object.freeze(${JSON.stringify({
      artifact: 'lib/meta-theory/fixed-point-source.lino',
      schema: metadata.schema,
      representation: metadata.representation,
      upstreamModel: metadata.upstreamModel,
      sourceNodes: metadata.declaredNodeCount,
      roots: metadata.declaredRootCount,
      provenance: 'link-native',
      compiledFromExternalSemanticDescription: false,
    }, null, 2)});\n` +
    `export default \`${serialized}\`;\n`,
);
