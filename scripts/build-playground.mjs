#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { parseJavaScriptAst } from './generate-linked-runtime.mjs';
import { generateJavaScript } from './linked-runtime-codegen.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const jsRequire = createRequire(path.join(repoRoot, 'js', 'package.json'));
const esbuild = jsRequire('esbuild');

const sourceFile = path.join(repoRoot, 'js', 'src', 'rml-links.mjs');
const outputFile = path.join(repoRoot, 'docs', 'playground', 'rml-playground-runtime.mjs');

const browserShims = `const process = {
  argv: [],
  env: {},
  cwd: () => '/',
  exit(code = 0) {
    throw new Error(\`The RML CLI is not available in the browser playground (exit \${code}).\`);
  },
};

function unavailableNodeApi(name) {
  return () => {
    throw new Error(\`\${name} is not available in the browser playground. Paste dependencies inline instead.\`);
  };
}

const fs = {
  readFileSync: unavailableNodeApi('File system reads'),
  writeFileSync: unavailableNodeApi('File system writes'),
};

const path = {
  basename(input) {
    const value = String(input || '').replace(/\\\\/g, '/').replace(/\\/+$/g, '');
    const index = value.lastIndexOf('/');
    return index === -1 ? value : value.slice(index + 1);
  },
  dirname(input) {
    const value = String(input || '').replace(/\\\\/g, '/').replace(/\\/+$/g, '');
    const index = value.lastIndexOf('/');
    if (index <= 0) return '/';
    return value.slice(0, index);
  },
  isAbsolute(input) {
    return String(input || '').startsWith('/');
  },
  resolve(...parts) {
    const joined = parts.filter(Boolean).map(String).join('/');
    const absolute = joined.startsWith('/') ? joined : \`/\${joined}\`;
    const stack = [];
    for (const part of absolute.split('/')) {
      if (!part || part === '.') continue;
      if (part === '..') stack.pop();
      else stack.push(part);
    }
    return \`/\${stack.join('/')}\`;
  },
};

function spawnSync() {
  return {
    status: 127,
    stdout: '',
    stderr: 'External solver processes are not available in the browser playground.',
    error: new Error('External solver processes are not available in the browser playground.'),
  };
}
`;

function browserEntrySource() {
  const syntax = parseJavaScriptAst(fs.readFileSync(sourceFile, 'utf8'), repoRoot);
  const shims = parseJavaScriptAst(browserShims, repoRoot);
  const nodeImports = new Set(['node:fs', 'node:url', 'node:path', 'node:child_process']);
  let removed = 0;
  syntax.program.body = syntax.program.body.filter(statement => {
    if (statement.type === 'ImportDeclaration' && nodeImports.has(statement.source.value)) { removed += 1; return false; }
    return true;
  });
  if (removed !== nodeImports.size) throw new Error('Browser adapter expected the four explicit Node capability imports');
  const containsPathToFileURL = value => value && typeof value === 'object' &&
    ((value.type === 'Identifier' && value.name === 'pathToFileURL') || Object.values(value).some(containsPathToFileURL));
  const guards = syntax.program.body.filter(statement => statement.type === 'IfStatement' && containsPathToFileURL(statement.test));
  if (guards.length !== 1) throw new Error('Browser adapter expected one explicit Node CLI entry guard');
  guards[0].test = { type: 'BooleanLiteral', value: false };
  delete syntax.program.interpreter;
  syntax.program.body.unshift(...shims.program.body);
  return generateJavaScript(syntax);
}

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
await esbuild.build({
  absWorkingDir: path.join(repoRoot, 'js'),
  nodePaths: [path.join(repoRoot, 'js', 'node_modules')],
  stdin: {
    contents: browserEntrySource(),
    resolveDir: path.dirname(sourceFile),
    sourcefile: 'rml-links-browser-entry.mjs',
    loader: 'js',
  },
  outfile: outputFile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  // Keep dependency module identifiers relative to this logical checkout rather
  // than leaking the physical location of an installed-provider symlink.
  preserveSymlinks: true,
  target: 'es2020',
  treeShaking: true,
  legalComments: 'inline',
  banner: {
    js: '// Generated by scripts/build-playground.mjs; do not edit by hand.',
  },
});
console.log(`Wrote ${path.relative(repoRoot, outputFile)}`);
